let passed = 0;
let total = 0;
async function test(name, fn) {
  total++;
  try {
    await fn();
    console.log(`  ✓ PASS: ${name}`);
    passed++;
  } catch (err) {
    console.error(`  ✗ FAIL: ${name}`);
    console.error(`    ${err.message}`);
    process.exitCode = 1;
  }
}

// 1. Classification Tests
await test("B8: Standard video item classified as VIDEO", () => {
  const item = { itemType: "video", isShortsLike: false, title: "Test Video" };
  assert.strictEqual(classifyItemType(item), "VIDEO");
});

await test("B8: Shorts-like video classified as SHORTS", () => {
  const item1 = { itemType: "video", isShortsLike: true, title: "Shorts Video" };
  const item2 = { itemType: "shorts_like", isShortsLike: false, title: "Shorts" };
  const item3 = { videoId: "abc", is_shorts_like: true, title: "Shorts" };

  assert.strictEqual(classifyItemType(item1), "SHORTS");
  assert.strictEqual(classifyItemType(item2), "SHORTS");
  assert.strictEqual(classifyItemType(item3), "SHORTS");
});

await test("B8: Channel item classified as CHANNELS", () => {
  const item = { itemType: "channel", channelId: "UC123", title: "My Channel" };
  assert.strictEqual(classifyItemType(item), "CHANNELS");
});

await test("B8: Playlist item classified as PLAYLISTS", () => {
  const item = { itemType: "playlist", playlistId: "PL123", title: "My Playlist" };
  assert.strictEqual(classifyItemType(item), "PLAYLISTS");
});

// 2. Filter Summary and Filtering Tests
await test("B7: computeFilterSummary accurately counts all 4 item types", () => {
  const items = [
    { itemType: "video", isShortsLike: false },
    { itemType: "video", isShortsLike: false },
    { itemType: "video", isShortsLike: true },
    { itemType: "channel" },
    { itemType: "playlist" },
    { custom: "data" },
  ];

  const summary = computeFilterSummary(items);
  assert.strictEqual(summary.total_videos, 2);
  assert.strictEqual(summary.total_shorts, 1);
  assert.strictEqual(summary.total_channels, 1);
  assert.strictEqual(summary.total_playlists, 1);
  assert.strictEqual(summary.total_unknown, 1);
});

await test("B7: filterEnvelopeItems strictly isolates VIDEO from SHORTS", () => {
  const items = [
    { id: 1, itemType: "video", isShortsLike: false },
    { id: 2, itemType: "video", isShortsLike: true },
    { id: 3, itemType: "channel" },
  ];

  const videos = filterEnvelopeItems(items, "VIDEO");
  const shorts = filterEnvelopeItems(items, "SHORTS");
  const channels = filterEnvelopeItems(items, "CHANNELS");

  assert.strictEqual(videos.length, 1);
  assert.strictEqual(videos[0].id, 1);
  assert.strictEqual(shorts.length, 1);
  assert.strictEqual(shorts[0].id, 2);
  assert.strictEqual(channels.length, 1);
  assert.strictEqual(channels[0].id, 3);
});

