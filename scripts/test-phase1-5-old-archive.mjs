// 4. SHA-256 Digest Tests
await test("B6: computeSha256 produces 64-char lowercase hex digest", () => {
  const digest = computeSha256("test-data-for-archive");
  assert.strictEqual(typeof digest, "string");
  assert.strictEqual(digest.length, 64);
  assert.strictEqual(digest, digest.toLowerCase());
});

// 5. ZIP Generation & Pure Node Extraction
await test("B3 & B4: extractZipEntries reads ZIP generated by pure Node zip-builder", () => {
  const testFiles = [
    { filename: "manifest.json", data: JSON.stringify({ manifestId: "zip_manifest_1", items: [{ itemType: "video" }] }) },
    { filename: "parts/part-1.json", data: JSON.stringify([{ itemType: "channel" }]) },
  ];
  const zipBuffer = createZipArchive(testFiles);
  const entries = extractZipEntries(zipBuffer);

  assert.strictEqual(entries.length, 2);
  assert.strictEqual(entries[0].filename, "manifest.json");
  assert.strictEqual(entries[1].filename, "parts/part-1.json");
});

await test("B4: extractZipEntries throws Security Violation on Zip-Slip path traversal (..)", () => {
  // Construct zip header with malicious path
  const maliciousFile = [{ filename: "../../etc/passwd", data: "malicious" }];
  const zipBuffer = createZipArchive(maliciousFile);

  assert.throws(
    () => extractZipEntries(zipBuffer),
    /Security Violation.*path traversal/
  );
});

await test("B4: extractZipEntries throws Security Violation on absolute root path (/root)", () => {
  const maliciousFile = [{ filename: "/var/log/secret.txt", data: "malicious" }];
  const zipBuffer = createZipArchive(maliciousFile);

  assert.throws(
    () => extractZipEntries(zipBuffer),
    /Security Violation.*path traversal/
  );
});

// 6. Manifest Envelope & Preserved Timestamps
await test("B1 & B2: parseRawBufferToEnvelope preserves authentic timestamps without fabrication", async () => {
  const originalFetchedAt = "2026-04-12T10:15:00.000Z";
  const json = JSON.stringify({
    manifestId: "historic_manifest_101",
    metadata: {
      fetchedAt: originalFetchedAt,
      exportedAt: "2026-04-12T11:00:00.000Z",
    },
    items: [
      { itemType: "video", title: "Historic Video" },
      { itemType: "video", isShortsLike: true, title: "Historic Short" },
    ],
  });

  const buffer = Buffer.from(json, "utf8");
  const envelope = await parseRawBufferToEnvelope(buffer, "historic_manifest.json");

  assert.strictEqual(envelope.schema_version, "1.0.0");
  assert.strictEqual(envelope.manifest_metadata.manifest_id, "historic_manifest_101");
  assert.strictEqual(envelope.manifest_metadata.source_created_at, originalFetchedAt);
  assert.strictEqual(envelope.manifest_metadata.source_exported_at, "2026-04-12T11:00:00.000Z");
  assert.strictEqual(envelope.manifest_metadata.record_count, 2);
  assert.strictEqual(envelope.manifest_metadata.filter_summary.total_videos, 1);
  assert.strictEqual(envelope.manifest_metadata.filter_summary.total_shorts, 1);
});

await test("B2: Missing historical timestamps are left null (never fabricated)", async () => {
  const json = JSON.stringify([
    { title: "Item without timestamp", itemType: "channel" },
  ]);

  const buffer = Buffer.from(json, "utf8");
  const envelope = await parseRawBufferToEnvelope(buffer, "raw_export.json");

  assert.strictEqual(envelope.manifest_metadata.source_created_at, null);
  assert.strictEqual(envelope.manifest_metadata.source_exported_at, null);
  assert(envelope.manifest_metadata.imported_at, "imported_at must be populated with current time");
});

await test("B3: NDJSON format parses line-by-line objects into envelope items", async () => {
  const ndjson = [
    JSON.stringify({ itemType: "video", title: "Line 1" }),
    JSON.stringify({ itemType: "video", isShortsLike: true, title: "Line 2" }),
    JSON.stringify({ itemType: "channel", title: "Line 3" }),
  ].join("\n");

  const buffer = Buffer.from(ndjson, "utf8");
  const envelope = await parseRawBufferToEnvelope(buffer, "records.ndjson");

  assert.strictEqual(envelope.manifest_metadata.source_format, "ndjson");
  assert.strictEqual(envelope.payload.items.length, 3);
  assert.strictEqual(envelope.manifest_metadata.filter_summary.total_videos, 1);
  assert.strictEqual(envelope.manifest_metadata.filter_summary.total_shorts, 1);
  assert.strictEqual(envelope.manifest_metadata.filter_summary.total_channels, 1);
});

